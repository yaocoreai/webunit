import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { loadPlatformEnvironment } from './environment.mjs';
import { collectStringArrayProperties, findCallObjects, parseTypescript, readBooleanLiteral, readObjectProperty, readStringLiteral } from './typescript-static.mjs';
import { resolveRenderer } from '../src/platform/build/renderer.mjs';

const appRoot = new URL('../', import.meta.url);
const sourceRoot = new URL('src/theme/', appRoot);
const datasModulesRoot = new URL('src/theme/datas/modules/', appRoot);
const manifestPath = new URL('src/manifest.ts', appRoot);
const platformEnv = process.env.PLATFORM_ENV ?? 'node';
await loadPlatformEnvironment(platformEnv, new URL('../../', import.meta.url));
await resolveRenderer(appRoot, process.env.PLATFORM_RENDERER ?? 'theme');

async function writeCmsInstallationRegistry(includePresentation) {
  const content = includePresentation
    ? `${[
      '// This file is auto-generated by scripts/generate-registry.mjs.',
      '// Do not edit manually.',
      '',
      "import { createInstallationSettings } from '@/platform/theme/installation/settings';",
      '',
      'export async function readCmsInstallationManifest() {',
      "  const [{ sectionSettings, templateSettings }, { layoutSetting, siteManifest }] = await Promise.all([",
      "    import('@/platform/generated/theme/setting-runtime'),",
      "    import('@/platform/generated/theme/definition'),",
      '  ]);',
      '  const [manifest, layout, templates, sections] = await Promise.all([',
      '    siteManifest().then((module) => module.default),',
      '    layoutSetting().then((module) => module.default),',
      '    Promise.all(',
      '      Object.entries(templateSettings)',
      '        .sort(([left], [right]) => left.localeCompare(right))',
      '        .map(async ([, load]) => (await load()).default),',
      '    ),',
      '    Promise.all(',
      '      Object.entries(sectionSettings)',
      '        .sort(([left], [right]) => left.localeCompare(right))',
      '        .map(async ([, load]) => (await load()).default),',
      '    ),',
      '  ]);',
      '  return createInstallationSettings({ manifest, layout, templates, sections });',
      '}',
      '',
    ].join('\n')}\n`
    : `${[
      '// This file is auto-generated by scripts/generate-registry.mjs.',
      '// Do not edit manually.',
      '',
      "import manifest from '@/manifest';",
      '',
      'export async function readCmsInstallationManifest() {',
      '  return {',
      '    package: manifest.package ?? {},',
      '    viewport: manifest.viewport ?? { strategy: "responsive", minWidth: 375 },',
      '    installation: manifest.installation,',
      '    site: manifest.site,',
      '    menu: manifest.menu,',
      '    modules: manifest.modules,',
      '    seo: manifest.seo,',
      '    layout: null,',
      '    templates: [],',
      '    sections: [],',
      '    templateInstances: [],',
      '    resources: [],',
      '  } as const;',
      '}',
      '',
    ].join('\n')}\n`;
  const target = new URL('src/platform/generated/cms-installation.ts', appRoot);
  await mkdir(new URL('src/platform/generated/', appRoot), { recursive: true });
  const temporary = new URL(`${target.pathname}.tmp-${process.pid}`, target);
  await writeFile(temporary, content);
  await rename(temporary, target);
}

const discoverFeatures = async (kind, requiredFiles = ['setting.ts', 'render.astro']) => {
  const root = new URL(`${kind}/`, sourceRoot);
  const entries = await readdir(root, { withFileTypes: true });
  const features = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const files = await readdir(new URL(`${entry.name}/`, root));
    const missing = requiredFiles.filter((file) => !files.includes(file));
    if (missing.length) {
      if (files.includes('setting.ts') || files.includes('render.astro')) {
        throw new Error(`${kind}/${entry.name} requires ${missing.join(', ')}`);
      }
      continue;
    }

    features.push(entry.name);
  }

  return features.sort();
};

const createMap = (name, keys, path, file) => [
  `export const ${name} = {`,
  ...keys.map((key) => `  '${key}': () => import('@/${path}/${key}/${file}'),`),
  '} as const;',
].join('\n');

const createSettingMap = (name, keys, path) => [
  `export const ${name} = {`,
  ...keys.map((key) => `  '${key}': async () => { const module = await import('@/${path}/${key}/setting'); return { ...module, default: { ...module.default, key: '${key}' } }; },`),
  '} as const;',
].join('\n');

const readTemplateFrames = async (templates) => Object.fromEntries(await Promise.all(templates.map(async (key) => {
  const setting = await readFile(new URL(`templates/${key}/setting.ts`, sourceRoot), 'utf8');
  const definition = findCallObjects(parseTypescript(setting, `theme/templates/${key}/setting.ts`), 'defineTemplate')[0];
  if (!definition) throw new Error(`Template requires defineTemplate({...}): ${key}`);
  const frame = readStringLiteral(readObjectProperty(definition, 'frame')) ?? '';
  return [key, frame];
})));

const readTemplateGroups = async (templates) => Object.fromEntries(await Promise.all(templates.map(async (key) => {
  const setting = await readFile(new URL(`templates/${key}/setting.ts`, sourceRoot), 'utf8');
  return [key, collectStringArrayProperties(parseTypescript(setting, `theme/templates/${key}/setting.ts`), 'groups')];
})));

const readSectionGroups = async (sections) => Object.fromEntries(await Promise.all(sections.map(async (key) => {
  const setting = await readFile(new URL(`sections/${key}/setting.ts`, sourceRoot), 'utf8');
  return [key, collectStringArrayProperties(parseTypescript(setting, `theme/sections/${key}/setting.ts`), 'groups')];
})));

const createValueMap = (name, values) => [
  `export const ${name} = {`,
  ...Object.entries(values).map(([key, value]) => `  '${key}': '${value}',`),
  '} as const;',
].join('\n');

const typeName = (key, suffix) => `${key.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join('')}${suffix}`;

const unionType = (keys, suffix, fallback) => keys.length
  ? keys.map((key) => typeName(key, suffix)).join(' | ')
  : fallback;

const rendererTypes = (moduleKeys, modulesByKey) => {
  const parentKeys = [...new Set(moduleKeys.map((key) => modulesByKey[key]?.parentKey).filter(Boolean))];
  return {
    module: unionType(moduleKeys, 'Module', 'ThemeModule'),
    entry: unionType(moduleKeys, 'Entry', 'ModuleEntry'),
    parentModule: unionType(parentKeys, 'Module', 'never'),
    parentEntry: unionType(parentKeys, 'Entry', 'never'),
  };
};

const createThemeRenderRegistry = (templates, templateFrames, sections) => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  createValueMap('templateFrames', templateFrames),
  '',
  createMap('templateRenders', templates, 'theme/templates', 'render.astro'),
  '',
  createMap('sectionRenders', sections, 'theme/sections', 'render.astro'),
  '',
].join('\n')}\n`;

const createThemePreviewRegistry = (templates) => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  createMap('templateSlotPreviews', templates, 'theme/templates', 'slots.astro'),
  '',
].join('\n')}\n`;

const createThemeSettingRegistry = (templateDefinitions, sections) => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  createSettingMap('templateSettings', templateDefinitions, 'theme/templates'),
  '',
  createSettingMap('sectionSettings', sections, 'theme/sections'),
  '',
].join('\n')}\n`;

const createSiteManifestRegistry = () => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  "export const siteManifest = () => import('@/manifest');",
  "export const layoutSetting = () => import('@/theme/layout/setting');",
  "export const errorSetting = async () => { const module = await import('@/theme/templates/error/setting'); return { ...module, default: { ...module.default, key: 'error' } }; };",
  '',
].join('\n')}\n`;

const createThemeTypes = (templates, templateModules, sections, sectionModules, errorSections, modules) => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  `import type { ${errorSections.length ? 'InferErrorSectionRenderer, ' : ''}InferLayoutInstance, InferSectionRenderer, InferTemplateInstance, InferTemplateRenderer } from '@/platform/theme/render/render-instance';`,
  "import type { CmsAsset, CmsMenu, ModuleEntry } from '@/platform/theme/content/public';",
  "import type { ThemeModule } from '@/platform/theme/render/model';",
  `import type { Site, ${modules.flatMap((module) => [
    ...(module.templateKey || modules.some((candidate) => candidate.parentKey === module.key) ? [typeName(module.key, 'Module')] : []),
    typeName(module.key, 'Entry'),
  ]).join(', ')} } from '@/theme/types';`,
  '',
  `export type TemplateKey = ${templates.map((key) => JSON.stringify(key)).join(' | ') || 'never'};`,
  `export type SectionKey = ${sections.map((key) => JSON.stringify(key)).join(' | ') || 'never'};`,
  '',
  'type ThemeSettingResources = Readonly<{',
  '  file: CmsAsset;',
  '  menu: CmsMenu;',
  '  modules: Readonly<{',
  ...modules.map((module) => `    '${module.key}': ${typeName(module.key, 'Entry')};`),
  '  }>;',
  '}>;',
  '',
  "export type Layout = InferLayoutInstance<typeof import('@/theme/layout/setting').default, ThemeSettingResources>;",
  "export type Error = InferTemplateInstance<typeof import('@/theme/templates/error/setting').default, ThemeSettingResources>;",
  ...templates.map((key) => {
    const types = rendererTypes(templateModules[key], Object.fromEntries(modules.map((module) => [module.key, module])));
    return `export type ${typeName(key, 'Template')} = InferTemplateRenderer<typeof import('@/theme/templates/${key}/setting').default, ThemeSettingResources, Site, ${types.module}, ${types.entry}, ${types.parentModule}, ${types.parentEntry}>;`;
  }),
  ...sections.map((key) => {
    if (errorSections.includes(key)) return `export type ${typeName(key, 'Section')} = InferErrorSectionRenderer<typeof import('@/theme/sections/${key}/setting').default, ThemeSettingResources, Site>;`;
    const types = rendererTypes(sectionModules[key], Object.fromEntries(modules.map((module) => [module.key, module])));
    return `export type ${typeName(key, 'Section')} = InferSectionRenderer<typeof import('@/theme/sections/${key}/setting').default, ThemeSettingResources, Site, ${types.module}, ${types.entry}, ${types.parentModule}, ${types.parentEntry}>;`;
  }),
  '',
].join('\n')}\n`;

const createDatasRegistry = (modules, themeModules, templateDatas) => `${[
  '// This file is auto-generated by scripts/generate-registry.mjs.',
  '// Do not edit manually.',
  '',
  ...modules.map((module, index) => `import module${index}${module.hasTranslations ? `, { translations as module${index}Translations }` : ''} from '@/theme/datas/modules/${module.key}';`),
  ...modules.flatMap((module, moduleIndex) => module.entries.map((entry, entryIndex) => `import { translations as module${moduleIndex}Entry${entryIndex}Translations } from '@/theme/datas/modules/${module.key}/${entry}';`)),
  ...templateDatas.filter((template) => template.hasTranslations).map((template, index) => `import { translations as template${index}Translations } from '@/theme/datas/template/${template.key}.default';`),
  '',
  'export const datasModules = {',
  ...modules.map((module, index) => `  '${module.key}': module${index},`),
  '} as const;',
  '',
  'export const datasModuleSchemas = [',
  ...themeModules.map((module) => `  { key: '${module.key}', kind: '${module.kind}'${module.sitemap ? ', sitemap: true' : ''}${module.parentKey ? `, parentKey: '${module.parentKey}'` : ''}${module.routePrefix !== undefined ? `, routePrefix: '${module.routePrefix}'` : ''}${module.templateKey ? `, templateKey: '${module.templateKey}'` : ''} },`),
  '] as const;',
  '',
  'export const datasTemplateTranslations = [',
  ...templateDatas.filter((template) => template.hasTranslations).map((template, index) => `  ...template${index}Translations.map((translation) => ({ ...translation, content: { '${template.key}.default': translation.content } })),`),
  '] as const;',
  '',
  'export const datasModuleTranslations = {',
  ...modules.map((module, index) => `  '${module.key}': ${module.hasTranslations ? `module${index}Translations` : '[]'},`),
  '} as const;',
  '',
  'export const datasModuleEntryTranslations = {',
  ...modules.map((module, moduleIndex) => `  '${module.key}': { ${module.entries.map((entry, entryIndex) => `'${entry}': module${moduleIndex}Entry${entryIndex}Translations`).join(', ')} },`),
  '} as const;',
  '',
  'export type DatasModuleKey = keyof typeof datasModules;',
  '',
].join('\n')}\n`;

const templateDefinitions = await discoverFeatures('templates', ['setting.ts', 'render.astro', 'slots.astro']);
const templates = templateDefinitions;
const templateFrames = await readTemplateFrames(templateDefinitions);
const templateGroups = await readTemplateGroups(templates);
const sections = await discoverFeatures('sections');
const sectionGroups = await readSectionGroups(sections);
const errorSettingSource = await readFile(new URL('templates/error/setting.ts', sourceRoot), 'utf8');
const errorSettingAst = parseTypescript(errorSettingSource, 'theme/templates/error/setting.ts');
const errorGroups = collectStringArrayProperties(errorSettingAst, 'groups');
const datasModuleKeys = (await readdir(datasModulesRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const manifestSource = await readFile(manifestPath, 'utf8');
const themeModuleBlocks = findCallObjects(parseTypescript(manifestSource, 'src/manifest.ts'), 'defineSiteManifestModule');
const themeModules = themeModuleBlocks.flatMap((block) => {
  const key = readStringLiteral(readObjectProperty(block, 'key'));
  if (!key) return [];
  const kind = readStringLiteral(readObjectProperty(block, 'kind')) ?? 'page';
  if (kind !== 'page' && kind !== 'model') throw new Error(`Invalid module kind: ${key}`);
  const declaredTemplateKey = readStringLiteral(readObjectProperty(block, 'templateKey'));
  if (kind === 'model' && declaredTemplateKey) throw new Error(`Model module cannot declare templateKey: ${key}`);
  const templateKey = kind === 'page' ? (declaredTemplateKey ?? key) : undefined;
  return [{ key, kind, templateKey, sitemap: readBooleanLiteral(readObjectProperty(block, 'sitemap')) === true, routePrefix: readStringLiteral(readObjectProperty(block, 'routePrefix')), parentKey: readStringLiteral(readObjectProperty(block, 'parentKey')) }];
});
const themeModulesByKey = Object.fromEntries(themeModules.map((module) => [module.key, module]));
for (const module of themeModules) {
  if (module.templateKey && !templates.includes(module.templateKey)) throw new Error(`Unknown Theme template: ${module.key} -> ${module.templateKey}`);
  if (module.parentKey && !themeModulesByKey[module.parentKey]) throw new Error(`Unknown parent module: ${module.key} -> ${module.parentKey}`);
}
const datasModules = await Promise.all(datasModuleKeys.map(async (key) => {
  const indexSource = await readFile(new URL(`${key}/index.ts`, datasModulesRoot), 'utf8');
  return {
  key,
  hasTranslations: /\bexport\s+const\s+translations\b/.test(indexSource),
  entries: (await readdir(new URL(`${key}/`, datasModulesRoot)))
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
    .map((file) => file.slice(0, -3))
    .sort(),
  };
}));
for (const module of datasModules) {
  if (/\bdefineModuleQueryEntries\s*\(/.test(await readFile(new URL(`${module.key}/index.ts`, datasModulesRoot), 'utf8')) && module.entries.length) throw new Error(`Query Entries Module cannot contain static Entry files: ${module.key}`);
}
const templateDatas = await Promise.all(templateDefinitions.map(async (key) => ({
  key,
  hasTranslations: /\bexport\s+const\s+translations\b/.test(await readFile(new URL(`src/theme/datas/template/${key}.default.ts`, appRoot), 'utf8')),
})));
const templateModules = Object.fromEntries(templates.map((template) => [
  template,
  themeModules.filter((module) => module.templateKey === template).map((module) => module.key),
]));
const sectionModules = Object.fromEntries(sections.map((section) => {
  const compatibleTemplates = templates.filter((template) => templateGroups[template].some((group) => sectionGroups[section].includes(group)));
  return [section, [...new Set(compatibleTemplates.flatMap((template) => templateModules[template]))]];
}));
const errorSections = sections.filter((section) => errorGroups.some((group) => sectionGroups[section].includes(group)));
const outputs = [
  [new URL('src/platform/generated/theme/render-runtime.ts', appRoot), createThemeRenderRegistry(templates, templateFrames, sections)],
  [new URL('src/platform/generated/theme/preview-runtime.ts', appRoot), createThemePreviewRegistry(templates)],
  [new URL('src/platform/generated/theme/setting-runtime.ts', appRoot), createThemeSettingRegistry(templateDefinitions, sections)],
  [new URL('src/platform/generated/theme/definition.ts', appRoot), createSiteManifestRegistry()],
  [new URL('src/platform/generated/theme/types.ts', appRoot), createThemeTypes(templates, templateModules, sections, sectionModules, errorSections, themeModules)],
  [new URL('src/platform/generated/datas-registry.ts', appRoot), createDatasRegistry(datasModules, themeModules, templateDatas)],
];

await mkdir(new URL('src/platform/generated/', appRoot), { recursive: true });
await Promise.all(outputs.map(async ([target, content]) => {
  await mkdir(new URL('.', target), { recursive: true });
  const temporary = new URL(`${target.pathname}.tmp-${process.pid}`, target);
  await writeFile(temporary, content);
  await rename(temporary, target);
}));
await writeCmsInstallationRegistry(true);

console.log(`Generated Theme registries (${templates.length} templates, ${sections.length} sections, ${datasModules.length} Datas modules).`);
